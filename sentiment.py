def get_sentiment(text):
    text = text.lower()
    text = text.replace("անհաջող", "ձախող")

    positive_count = 0
    for word in positive_words:
        positive_count = positive_count + text.count(word)

    negative_count = 0
    for word in negative_words:
        negative_count = negative_count + text.count(word)

    neutral_count = 1

    total = positive_count + negative_count + neutral_count

    positive_percent = positive_count / total * 100
    negative_percent = negative_count / total * 100
    neutral_percent = neutral_count / total * 100

    if positive_count > negative_count:
        label = "Դրական 🙂"
    elif negative_count > positive_count:
        label = "Բացասական 🙁"
    else:
        label = "Չեզոք 😐"

    return label, positive_percent, negative_percent, neutral_percent


